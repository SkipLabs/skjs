#!/usr/bin/env bash
#
# survey-projects.sh — run try-project.sh over a fixed list of real-world
# TypeScript projects and print SKJS's current support status across them.
#
# Usage:
#   scripts/survey-projects.sh
#
# Environment (forwarded to try-project.sh):
#   SKJS_BIN, STUBS, WORKDIR, KEEP_CLONE   (see try-project.sh)
#
# Writes a markdown report to $WORKDIR/support-status.md and prints a table.
# The project list is pinned to tags so the survey is reproducible; bump a ref
# to re-measure against a newer release.

set -u -o pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORKDIR="${WORKDIR:-${PROJECT_ROOT}/.project-survey}"
TRY="${PROJECT_ROOT}/scripts/try-project.sh"
export WORKDIR

# git-url | ref | src-subdir   (the project name is the url's last path segment)
PROJECTS=(
  "https://github.com/js-sdsl/js-sdsl|v4.4.2|src"
  "https://github.com/vultix/ts-results|v3.0.0|src"
  "https://github.com/supermacro/neverthrow|v8.2.0|src"
  "https://github.com/sodiray/radash|v12.1.1|src"
  "https://github.com/immerjs/immer|v11.1.15|src"
  "https://github.com/gcanti/fp-ts|2.16.9|src"
  "https://github.com/colinhacks/zod|v3.24.1|src"
  "https://github.com/fabian-hiller/valibot|v1.4.2|library/src"
)

reports="${WORKDIR}/reports"
mkdir -p "$reports"

names=()
for entry in "${PROJECTS[@]}"; do
  IFS='|' read -r url ref src <<<"$entry"
  name="$(basename "$url" .git)"
  names+=("$name")
  "$TRY" "$url" "$ref" "$src" || echo "survey: try-project failed for $name" >&2
done

# --- aggregate ---------------------------------------------------------------
report_md="${WORKDIR}/support-status.md"
REPORTS_DIR="$reports" REPORT_MD="$report_md" python3 - "${names[@]}" <<'PY'
import json, os, sys

names = sys.argv[1:]
reports_dir = os.environ["REPORTS_DIR"]
rows = []
for name in names:
    path = os.path.join(reports_dir, f"{name}.json")
    try:
        with open(path) as fh:
            rows.append(json.load(fh))
    except FileNotFoundError:
        rows.append({"name": name, "status": "missing", "files": 0, "clean_pct": 0,
                     "by_category": {}, "warnings": 0, "top_errors": [], "ref": "?",
                     "crash_reason": "no report produced"})

STATUS_ORDER = {"good": 0, "partial": 1, "weak": 2, "unsupported": 3,
                "crash": 4, "no-ts": 5, "missing": 6}
rows.sort(key=lambda r: (STATUS_ORDER.get(r.get("status"), 9), -r.get("clean_pct", 0)))

def cats(r):
    c = r.get("by_category", {}) or {}
    return c.get("feature", 0), c.get("type", 0), c.get("resolution", 0)

def blocker(r):
    if r.get("status") == "crash":
        return "CRASH: " + (r.get("crash_reason", "")[:48])
    te = r.get("top_errors") or []
    return (te[0][0][:48]) if te else "-"

# Console table.
hdr = f"{'project':<12} {'ref':<9} {'files':>5} {'clean':>6} {'feat':>4} {'type':>4} {'reso':>4} {'status':<11} top blocker"
print("\n" + hdr)
print("-" * len(hdr))
for r in rows:
    f, t, res = cats(r)
    clean = "-" if r.get("status") in ("crash", "no-ts", "missing") else f"{r.get('clean_pct',0):.0f}%"
    print(f"{r['name']:<12} {str(r.get('ref','?')):<9} {r.get('files',0):>5} {clean:>6} "
          f"{f:>4} {t:>4} {res:>4} {r.get('status','?'):<11} {blocker(r)}")

print("\nstatus: good ≥90% files clean · partial ≥60% · weak ≥20% · unsupported <20% · crash = checker aborted")
print("categories: feat = unsupported-feature errors (real subset gaps) · type = type rejections · "
      "reso = missing stub / path alias / declaration (often config, not a language gap)")

# Markdown report.
lines = ["# SKJS support status on real-world TypeScript projects", "",
         "Generated by `scripts/survey-projects.sh`. Each project is checked with "
         "`scripts/try-project.sh` (SKJS over the project's `.ts` source, pinned to a tag).", "",
         "| project | ref | files | clean | feat | type | reso | status | top blocker |",
         "| --- | --- | --: | --: | --: | --: | --: | --- | --- |"]
for r in rows:
    f, t, res = cats(r)
    clean = "—" if r.get("status") in ("crash", "no-ts", "missing") else f"{r.get('clean_pct',0):.0f}%"
    lines.append(f"| [{r['name']}]({r.get('url','')}) | `{r.get('ref','?')}` | {r.get('files',0)} | "
                 f"{clean} | {f} | {t} | {res} | {r.get('status','?')} | {blocker(r).replace('|','\\|')} |")
lines += ["",
          "- **status**: good ≥90% files clean · partial ≥60% · weak ≥20% · unsupported <20% · crash = checker aborted",
          "- **feat** = unsupported-feature errors (genuine subset gaps) · **type** = type rejections · "
          "**reso** = missing stub / path alias / declaration (often config, not a language gap)"]
with open(os.environ["REPORT_MD"], "w") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"\nmarkdown report: {os.environ['REPORT_MD']}")
PY
