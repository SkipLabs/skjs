#!/usr/bin/env python3
"""Build and consistency tooling for the SKJS soundness corpus.

Usage:  python3 docs/tools/docs.py [gen|check|build|all]   (default: all)

  gen    Render docs/generated/*.tex from docs/ledger.yaml.
  check  Consistency checks (registry integrity, anchors, issue files and
         their GitHub mappings, temporal-marker and numeric-cross-reference
         lint, pin usage).
  build  gen + compile every .tex with pdflatex (two passes), keeping the
         .pdf next to its source. Auxiliary files live in docs/.texbuild/
         (git-ignored) so incremental recompilation stays warm.
  all    gen + check + build.
  repro  run each issue witness .ts against the pinned checker and assert
         its header verdict (needs the built binary + docker).

Exit status is non-zero if any check fails or any document fails to build.
"""

import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

DOCS = Path(__file__).resolve().parent.parent
REPO = DOCS.parent
GENERATED = DOCS / "generated"
TEXBUILD = DOCS / ".texbuild"
ISSUES = DOCS / "deep-dives" / "issues"
REPROS = ISSUES / "repros"

MAIN_TEX = DOCS / "skjs-type-soundness.tex"
DIVE_TEXS = sorted((DOCS / "deep-dives").glob("*.tex"))
ALL_TEXS = [MAIN_TEX] + DIVE_TEXS

STATUS_ENUM = {"proved", "assumed", "open", "violated"}
SUMMARY_BUCKETS = [
    ("proved", r"\emph{Proved}"),
    ("assumed", r"\emph{Assumed}"),
    ("open", r"\emph{Open}"),
    ("violated-witnessed",
     r"\emph{Violated, with an executed witness} (each with a GitHub issue "
     r"and an issue report under \texttt{deep-dives/issues/})"),
    ("violated-derived",
     r"\emph{Violated by code-level derivation} (no end-to-end run yet)"),
]

# Sentences that narrate document history rather than current state.
TEMPORAL_MARKERS = [
    "Verification update", "Status update", "has since", "At the time of writing",
    "previous draft", "earlier draft", "was wrong", "were wrong",
    "no longer contains", "originally proposed", "update below", "update above",
]

# Deep dives may not cite main-paper items by number (numbers drift).
NUMERIC_XREF = re.compile(
    r"main paper[^.\n]{0,60}?(Definition|Lemma|Theorem|Axiom|Obligation)[~ ]\d"
    r"|(Definition|Lemma|Theorem|Axiom|Obligation)[~ ]\d+ (of|in) the main paper"
    r"|its (Definition|Lemma|Theorem|Axiom|Obligation)[~ ]\d")


def load_ledger():
    with open(DOCS / "ledger.yaml") as f:
        return yaml.safe_load(f)


def esc_row(entry, cols):
    return " &\n  ".join(entry[c].strip() for c in cols) + r" \\"


MD_TOKEN = re.compile(r"\\texttt\{([a-z0-9-]+\.md)\}")
LONG_TT = re.compile(r"\\texttt\{([A-Za-z0-9_.:/-]{22,})\}")


def breakable(text):
    """Make long typewriter tokens line-breakable (\\path, url package)."""
    text = MD_TOKEN.sub(r"\\path{\1}", text)
    return LONG_TT.sub(r"\\path{\1}", text)


def badges(entry):
    return ", ".join("\\textsc{%s}" % s for s in entry["status"])


def overview_table(rows, label_col="Item"):
    out = []
    out.append(r"\begingroup")
    out.append(r"\renewcommand{\arraystretch}{1.2}")
    out.append(r"\small")
    out.append(r"\begin{longtable}{@{}"
               r">{\raggedright\arraybackslash}p{2.5cm}"
               r">{\raggedright\arraybackslash}p{8.6cm}"
               r">{\raggedright\arraybackslash}p{3.1cm}@{}}")
    header = (r"\toprule" "\n"
              r"\textbf{%s} & \textbf{Statement} & \textbf{Status} \\"
              "\n" r"\midrule") % label_col
    out += [header, r"\endfirsthead", header, r"\endhead",
            r"\midrule",
            r"\multicolumn{3}{r@{}}{\small\emph{Continued on next page}} \\",
            r"\endfoot", r"\bottomrule", r"\endlastfoot"]
    for e in rows:
        out.append("%s & %s & %s \\\\" % (
            e["id"], breakable(e["short"].strip()), badges(e)))
    out.append(r"\end{longtable}")
    out.append(r"\endgroup")
    return out


def detail_records(rows):
    """Full-width record per entry: the prose fields get the whole text
    width instead of a narrow table column."""
    out = []
    for e in rows:
        out.append(r"\medskip\par\noindent"
                   r"\textbf{%s}\quad(%s)\\*[0.15em]" % (e["id"], badges(e)))
        stmt = (e.get("statement") or "").strip() or e["short"].strip()
        out.append(breakable(stmt) + r"\\*[0.15em]")
        out.append(r"{\small\emph{Anchor:} %s}\par" % breakable(e["anchor"].strip()))
        out.append(r"\nopagebreak")
        out.append(breakable(e["status_note"].strip()))
        out.append("")
    return out


def gen(entries, papers=(), fixes=()):
    GENERATED.mkdir(exist_ok=True)
    warn = ("% GENERATED by docs/tools/docs.py from docs/ledger.yaml — do not edit.\n")

    # Main assumptions: overview table + full-width detail records.
    main_rows = [e for e in entries if e["table"] == "main"]
    out = [warn]
    out += overview_table(main_rows)
    out.append(r"\paragraph{Details.}\leavevmode")
    out += detail_records(main_rows)
    (GENERATED / "ledger-table.tex").write_text("\n".join(out) + "\n")

    # Series items: same two forms.
    series_rows = [e for e in entries if e["table"] == "series"]
    out = [warn]
    out += overview_table(series_rows)
    out.append(r"\paragraph{Details.}\leavevmode")
    out += detail_records(series_rows)
    (GENERATED / "ledger-series-table.tex").write_text("\n".join(out) + "\n")

    # Summary (grouped by bucket).
    out = [warn, r"\begin{itemize}"]
    for bucket, title in SUMMARY_BUCKETS:
        labels = [s["label"] for e in entries for s in (e.get("summary") or [])
                  if s["bucket"] == bucket]
        if labels:
            out.append(r"\item %s: %s." % (title, "; ".join(labels)))
    out.append(r"\end{itemize}")
    (GENERATED / "ledger-summary.tex").write_text("\n".join(out) + "\n")

    # Per-paper tables (short cells only: a table is the right form).
    # rows-X: rows the paper OWNS (provides the proof/refutation for).
    # imports-X: rows the paper CONSUMES (its review contract: each is an
    # axiom for the reviewer, with the registry's canonical statement).
    letters = "".join(pp["letter"] for pp in papers) or "ABCDEFG"
    for letter in letters:
        rows = [e for e in entries if e.get("owner") == letter]
        out = [warn]
        out.append(r"\begin{center}")
        out.append(r"\renewcommand{\arraystretch}{1.25}")
        out.append(r"\small")
        out.append(r"\begin{tabular}{@{}"
                   r">{\raggedright\arraybackslash}p{2.4cm}"
                   r">{\raggedright\arraybackslash}p{8.2cm}"
                   r">{\raggedright\arraybackslash}p{2.6cm}@{}}")
        out.append(r"\toprule")
        out.append(r"\textbf{Row} & \textbf{Statement} & \textbf{Status} \\")
        out.append(r"\midrule")
        for e in rows:
            out.append("%s & %s & %s \\\\" % (
                e["id"], breakable(e["short"].strip()), badges(e)))
        out.append(r"\bottomrule")
        out.append(r"\end{tabular}")
        out.append(r"\end{center}")
        (GENERATED / ("rows-%s.tex" % letter)).write_text("\n".join(out) + "\n")

        imports = [e for e in entries
                   if letter in (e.get("consumers") or [])]
        out = [warn]
        if not imports:
            out.append(r"\noindent\emph{None beyond the main paper's "
                       r"definitions.}")
        else:
            out.append(r"\begin{center}")
            out.append(r"\renewcommand{\arraystretch}{1.25}")
            out.append(r"\small")
            out.append(r"\begin{tabular}{@{}"
                       r">{\raggedright\arraybackslash}p{2.6cm}"
                       r">{\raggedright\arraybackslash}p{7.4cm}"
                       r">{\raggedright\arraybackslash}p{1.2cm}"
                       r">{\raggedright\arraybackslash}p{2.2cm}@{}}")
            out.append(r"\toprule")
            out.append(r"\textbf{Row} & \textbf{Canonical statement} & "
                       r"\textbf{Owner} & \textbf{Status} \\")
            out.append(r"\midrule")
            for e in imports:
                out.append("%s & %s & %s & %s \\\\" % (
                    e["id"], breakable(e["short"].strip()),
                    e.get("owner", "?"), badges(e)))
            out.append(r"\bottomrule")
            out.append(r"\end{tabular}")
            out.append(r"\end{center}")
        (GENERATED / ("imports-%s.tex" % letter)).write_text(
            "\n".join(out) + "\n")

    # The deep-dives directory README is a generated navigation stub: the
    # series map is registry data, not an authored document.
    if papers:
        lines = [
            "<!-- GENERATED by docs/tools/docs.py from docs/ledger.yaml — "
            "do not edit. -->",
            "",
            "# Deep-Dive Series",
            "",
            "The evidence papers behind the registry rows of the main paper.",
            "Architecture, build instructions, and the review protocol:",
            "[`../README.md`](../README.md). The registry:",
            "[`../ledger.yaml`](../ledger.yaml).",
            "",
            "| Paper | File | Scope | Owns |",
            "|---|---|---|---|",
        ]
        for pp in papers:
            owned = ", ".join(e["id"] for e in entries
                              if e.get("owner") == pp["letter"])
            scope = " ".join(pp["scope"].split())
            lines.append("| %s | [`%s`](%s) | %s | %s |" % (
                pp["letter"], pp["file"], pp["file"], scope, owned))
        (DOCS / "deep-dives" / "README.md").write_text(
            "\n".join(lines) + "\n")

    # Verified fixes: violated items with a tested-but-unlanded patch.
    out = [warn]
    if not fixes:
        out.append(r"\noindent\emph{None recorded.}")
    else:
        out.append(r"\noindent\textbf{Verified fixes available (not "
                   r"landed).} Each has a tested patch under "
                   r"\path{deep-dives/issues/fixes/}; the row stays "
                   r"\textsc{violated} at the pinned revision until it lands.")
        out.append(r"\begin{itemize}")
        for fx in fixes:
            out.append("\\item \\path{%s} (row %s): %s" % (
                fx["issue"], fx["row"], " ".join(fx["verified"].split())))
        out.append(r"\end{itemize}")
    (GENERATED / "ledger-fixes.tex").write_text("\n".join(out) + "\n")

    print("gen: wrote %d generated files + series map" % (3 + 14 + 1))


def check(entries, fixes=(), papers=(), github_issues=None):
    problems = []
    github_issues = github_issues or {}
    letters = {pp["letter"] for pp in papers} or set("ABCDEFG")

    ids = [e["id"] for e in entries]
    if len(ids) != len(set(ids)):
        problems.append("ledger: duplicate ids")

    # Verified fixes: issue + patch must exist, row must resolve, patch
    # must still apply cleanly against the pinned source.
    id_set = set(ids)
    for fx in fixes:
        if not (ISSUES / fx["issue"]).exists():
            problems.append("fix references missing issue: %s" % fx["issue"])
        patch = REPROS.parent / "fixes" / fx["patch"]
        if not patch.exists():
            problems.append("fix references missing patch: %s" % fx["patch"])
        elif shutil.which("git"):
            r = subprocess.run(["git", "apply", "--check", str(patch)],
                               cwd=REPO, capture_output=True, text=True)
            if r.returncode != 0:
                problems.append("fix patch no longer applies: %s" % fx["patch"])
        if fx["row"] not in id_set:
            problems.append("fix references unknown row: %s" % fx["row"])

    OWNERS = letters | {"main"}
    for e in entries:
        if e.get("owner") not in OWNERS:
            problems.append("ledger %s: bad owner %r" % (e["id"], e.get("owner")))
        for c in e.get("consumers") or []:
            if c not in letters:
                problems.append("ledger %s: bad consumer %r" % (e["id"], c))
            if c == e.get("owner"):
                problems.append("ledger %s: owner listed as consumer" % e["id"])

    for e in entries:
        if len(e["status"]) != 1:
            problems.append("ledger %s: rows carry exactly one status "
                            "(split facets into sub-rows)" % e["id"])
        for st in e["status"]:
            if st not in STATUS_ENUM:
                problems.append("ledger %s: bad status %r" % (e["id"], st))
        for f in e.get("anchor_files") or []:
            if not (REPO / f).exists():
                problems.append("ledger %s: anchor file missing: %s" % (e["id"], f))
        for iss in e.get("issues") or []:
            if not (ISSUES / iss).exists():
                problems.append("ledger %s: issue file missing: %s" % (e["id"], iss))
        for s in e.get("summary") or []:
            if s["bucket"] not in {b for b, _ in SUMMARY_BUCKETS}:
                problems.append("ledger %s: bad summary bucket %r"
                                % (e["id"], s["bucket"]))

    # Every issue report corresponds to exactly one distinct GitHub issue.
    # This check is intentionally network-free; maintainers verify that a new
    # number resolves when adding it, while CI enforces totality and uniqueness.
    issue_files = {f.name for f in ISSUES.glob("*.md")}
    mapped_files = set(github_issues)
    for name in sorted(issue_files - mapped_files):
        problems.append("issue file has no GitHub issue mapping: %s" % name)
    for name in sorted(mapped_files - issue_files):
        problems.append("GitHub issue mapping names missing file: %s" % name)
    issue_numbers = list(github_issues.values())
    for name, number in github_issues.items():
        if not isinstance(number, int) or isinstance(number, bool) or number <= 0:
            problems.append("GitHub issue mapping %s has invalid number: %r"
                            % (name, number))
    if len(issue_numbers) != len(set(issue_numbers)):
        problems.append("GitHub issue mappings contain duplicate issue numbers")

    # Every issue file must be referenced from the ledger or some document.
    tex_blob = "\n".join(p.read_text() for p in ALL_TEXS)
    readme = (DOCS / "deep-dives" / "README.md").read_text() \
        + (DOCS / "README.md").read_text()
    ledger_issue_refs = {i for e in entries for i in (e.get("issues") or [])}
    for f in sorted(ISSUES.glob("*.md")):
        name = f.name
        if name not in ledger_issue_refs and name not in tex_blob \
                and name not in readme:
            problems.append("issue file unreferenced anywhere: %s" % name)

    # Issue-file mentions in documents must resolve.
    for p in ALL_TEXS + [DOCS / "deep-dives" / "README.md",
                         DOCS / "README.md"]:
        for m in re.finditer(r"([a-z0-9-]+\.md)", p.read_text()):
            name = m.group(1)
            if name in ("README.md",):
                continue
            if not (ISSUES / name).exists():
                problems.append("%s: dangling issue reference %s" % (p.name, name))

    # Temporal-marker lint.
    for p in ALL_TEXS:
        text = p.read_text()
        for marker in TEMPORAL_MARKERS:
            for m in re.finditer(re.escape(marker), text):
                line = text.count("\n", 0, m.start()) + 1
                problems.append("%s:%d: temporal marker %r" % (p.name, line, marker))

    # Numeric cross-references to the main paper (deep dives only).
    for p in DIVE_TEXS:
        text = p.read_text()
        for m in NUMERIC_XREF.finditer(text):
            line = text.count("\n", 0, m.start()) + 1
            problems.append("%s:%d: numeric main-paper reference %r"
                            % (p.name, line, m.group(0)))

    # Cross-dive dependency declaration: if dive X mentions dive Y, X must
    # consume at least one row owned by Y (the registry-mediated import
    # discipline; incidental mentions should cite the row instead).
    LETTER_OF = {"runtime-grounding": "A", "lattice-operations": "B",
                 "type-expansion": "C", "subtyping-validation": "D",
                 "subst-state-discipline": "E",
                 "refinement-invalidation": "F",
                 "literal-canonicalization": "G"}
    mention_re = re.compile(r"[Dd]eep [Dd]ive[s]?[~ ]([A-G])\b|paper[s]?[~ ]([A-G])\b")
    for p in DIVE_TEXS:
        x = LETTER_OF.get(p.stem)
        if not x:
            continue
        consumed_owners = {e["owner"] for e in entries
                           if x in (e.get("consumers") or [])}
        text = p.read_text()
        for m in mention_re.finditer(text):
            y = m.group(1) or m.group(2)
            if y and y != x and y not in consumed_owners:
                line = text.count("\n", 0, m.start()) + 1
                problems.append(
                    "%s:%d: mentions dive %s without a declared import "
                    "(no consumed row owned by %s)" % (p.name, line, y, y))

    # Registry-mediated imports: any row id a dive's prose USES (mentions by
    # its exact id) must be a row the dive owns, consumes, or whose owner it
    # legitimately references. Undeclared row usage is the import-drift class.
    LETTER_OF = {"runtime-grounding": "A", "lattice-operations": "B",
                 "type-expansion": "C", "subtyping-validation": "D",
                 "subst-state-discipline": "E",
                 "refinement-invalidation": "F",
                 "literal-canonicalization": "G"}
    all_ids = {e["id"] for e in entries}
    # ids long/distinctive enough that a bare textual match is meaningful
    lintable = {i for i in all_ids if "-" in i and i not in {"M1", "I-F"}}
    for p in DIVE_TEXS:
        x = LETTER_OF.get(p.stem)
        if not x:
            continue
        declared = {e["id"] for e in entries
                    if e.get("owner") == x or x in (e.get("consumers") or [])}
        text = p.read_text()
        for rid in sorted(lintable):
            if rid in declared:
                continue
            for m in re.finditer(r"(?<![\w-])" + re.escape(rid) + r"(?![\w-])", text):
                line = text.count("\n", 0, m.start()) + 1
                problems.append("%s:%d: names registry row %s without "
                                "owning/importing it (rule: reference "
                                "main-paper concepts by name, not row id; "
                                "declare the import if it is a real "
                                "dependency)" % (p.name, line, rid))
                break

    # Repro files: referenced-in-md must exist, and existing repros must be
    # referenced (witnesses are discrete, findable artifacts).
    md_blob = "\n".join(f.read_text() for f in sorted(ISSUES.glob("*.md")))
    referenced = set(re.findall(r"repros/([A-Za-z0-9_-]+\.ts)", md_blob))
    referenced_dirs = set(re.findall(r"repros/([A-Za-z0-9_-]+)(?=[/\s)\]`])",
                                     md_blob)) - {n[:-3] for n in referenced}
    for name in sorted(referenced):
        if not (REPROS / name).exists():
            problems.append("issue md references missing repro: %s" % name)
    for name in sorted(referenced_dirs):
        if not (REPROS / name / "main.ts").exists():
            problems.append("issue md references missing repro dir: %s" % name)
    if REPROS.exists():
        for f in sorted(REPROS.glob("*.ts")):
            if f.name not in referenced:
                problems.append("repro not referenced by any issue md: %s"
                                % f.name)
            head = f.read_text()[:400]
            if "// expect:" not in head:
                problems.append("repro missing // expect: header: %s"
                                % f.name)
        for d in sorted(p for p in REPROS.iterdir() if p.is_dir()):
            if d.name not in referenced_dirs:
                problems.append("repro dir not referenced by any issue md: %s"
                                % d.name)
            main_ts = d / "main.ts"
            if not main_ts.exists():
                problems.append("repro dir missing main.ts: %s" % d.name)
            elif "// expect:" not in main_ts.read_text()[:400]:
                problems.append("repro missing // expect: header: %s/main.ts"
                                % d.name)

    # \impl anchors inside dive/main texts: leading file token must exist.
    impl_re = re.compile(r"\\impl\{([^}]*)\}")
    file_re = re.compile(r"([A-Za-z0-9_/]+\.sk)")
    for p in ALL_TEXS:
        text = p.read_text()
        for m in impl_re.finditer(text):
            for fm in file_re.finditer(m.group(1)):
                fname = fm.group(1)
                cands = [REPO / "src" / fname, REPO / fname]
                if not any(c.exists() for c in cands):
                    line = text.count("\n", 0, m.start()) + 1
                    problems.append("%s:%d: impl anchor names missing file %s"
                                    % (p.name, line, fname))

    # No prose status vocabulary outside the generated tables. A status word
    # in \textsc{...} is fine inside generated/, but in an authored .tex it
    # restates registry state. A registry verdict token
    # (\textsc{proved|violated|open|assumed}) inside a paper-authored
    # tabular/longtable duplicates the status the registry owns and the
    # generated rows-* tables render; even one is a hard error. (Generated
    # tables live under generated/ and are \input, so they are never scanned
    # inline here.)
    status_re = re.compile(r"\\textsc\{(proved|violated|open|assumed)\}")
    for p in ALL_TEXS:
        text = p.read_text()
        for tm in re.finditer(r"\\begin\{(longtable|tabular)\}.*?\\end\{\1\}",
                              text, re.S):
            block = tm.group(0)
            if status_re.search(block):
                line = text.count("\n", 0, tm.start()) + 1
                problems.append("%s:%d: table restates a registry verdict "
                                "token (statuses live only in the registry; "
                                "render from generated/rows-* instead)"
                                % (p.name, line))

    # Pin usage: every document's \date must go through the shared pin.
    for p in ALL_TEXS:
        text = p.read_text()
        m = re.search(r"\\date\{([^}]*)\}", text)
        if not m or "\\skjspin" not in m.group(1):
            problems.append("%s: \\date does not use \\skjspin" % p.name)

    # Registry coverage: every main-table id should be citable — trivially
    # true via the generated table; warn if a series id appears nowhere.
    for e in entries:
        if e["table"] == "series" and e["id"] not in tex_blob:
            problems.append("warning: series id %s not mentioned in any .tex"
                            % e["id"])

    hard = [p for p in problems if not p.startswith("warning:")]
    for p in problems:
        print("check:", p)
    print("check: %d problem(s), %d warning(s)"
          % (len(hard), len(problems) - len(hard)))
    return len(hard) == 0


def build():
    ok = True
    for tex in ALL_TEXS:
        stem = tex.stem
        outdir = TEXBUILD / stem
        outdir.mkdir(parents=True, exist_ok=True)
        cmd = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
               "-output-directory", str(outdir), tex.name]
        good = True
        for _ in range(2):
            r = subprocess.run(cmd, cwd=tex.parent, capture_output=True,
                               text=True, errors="replace")
            if r.returncode != 0:
                good = False
                break
        log = (outdir / (stem + ".log"))
        logtext = log.read_text(errors="replace") if log.exists() else ""
        unresolved = len(re.findall(r"LaTeX Warning: Reference.*undefined", logtext))
        if good and unresolved == 0:
            shutil.copy2(outdir / (stem + ".pdf"), tex.with_suffix(".pdf"))
            pages = re.search(r"Output written on [^(]*\((\d+) pages",
                              logtext.replace("\n", ""))
            print("build: %s OK (%s pages)" % (stem, pages.group(1) if pages else "?"))
        else:
            ok = False
            print("build: %s FAILED (%s; unresolved=%d) — see %s"
                  % (stem, "compile error" if not good else "refs", unresolved, log))
            if not good:
                errs = [l for l in logtext.splitlines() if l.startswith("!")][:3]
                for e in errs:
                    print("  ", e)
    return ok




def repro():
    """Run each witness .ts against the pinned checker and assert its header
    verdict. The bridge from one-off probes to a build invariant."""
    if not REPROS.exists():
        print("repro: no repros/ directory"); return True
    ok = True
    targets = sorted(REPROS.glob("*.ts")) + sorted(REPROS.glob("*/main.ts"))
    for f in targets:
        head = f.read_text()[:600]
        m = re.search(r"// expect:\s*(accepted|rejected)", head)
        if not m:
            print("repro: %s has no expect header" % f.name); ok = False; continue
        want = m.group(1)
        # A pair-directory witness (repros/<name>/main.ts) is checked as its
        # whole directory so its sibling modules are on the module path.
        target = f.parent if f.name == "main.ts" else f
        rel = target.relative_to(REPO)
        label = (f.parent.name + "/" if f.name == "main.ts" else "") + f.name
        r = subprocess.run(
            ["make", "check-file-in-docker", "FILE=%s" % rel,
             "BIN=target/host/dev/skjs"],
            cwd=REPO, capture_output=True, text=True, errors="replace")
        got = "accepted" if r.returncode == 0 else "rejected"
        status = "OK " if got == want else "MISMATCH"
        if got != want:
            ok = False
        print("repro: %-8s %s (want %s, got %s)" % (status, label, want, got))
    return ok

def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "all"
    data = load_ledger()
    entries = data["entries"]
    ok = True
    if mode in ("gen", "build", "all"):
        gen(entries, data.get("papers") or [], data.get("fixes") or [])
    if mode in ("check", "all"):
        ok = check(entries, data.get("fixes") or [],
                   data.get("papers") or [],
                   data.get("github_issues") or {}) and ok
    if mode in ("build", "all"):
        ok = build() and ok
    if mode == "repro":
        ok = repro() and ok
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
